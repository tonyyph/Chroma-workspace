const catalog: Record<Language, Record<MessageKey, string>> = { en, vi };

export function translate(
  language: Language,
  key: MessageKey,
  parameters: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(parameters).reduce(
    (message, [parameter, value]) => message.replaceAll(`{${parameter}}`, String(value)),
    catalog[language][key],
  );
}
